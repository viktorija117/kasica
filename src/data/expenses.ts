import { endOfMonthKey, type MonthKey } from '../lib/dates'
import { supabase } from '../lib/supabase'
import type { Enums, Tables, TablesInsert, Views } from '../types/database'

export type Expense = Tables<'expenses'>
export type Necessity = Enums<'necessity'>
export type ExpenseSuggestion = Views<'expense_suggestions'>

/** The fields the expense form edits. Everything else is set by the database. */
export type ExpenseInput = Pick<
  TablesInsert<'expenses'>,
  'date' | 'category_id' | 'description' | 'amount' | 'necessity' | 'paid_by' | 'note'
>

/** Expenses of one month, newest day first. */
export async function fetchExpenses(householdId: string, month: MonthKey): Promise<Expense[]> {
  const { data, error } = await supabase
    .from('expenses')
    .select('*')
    .eq('household_id', householdId)
    .gte('date', month)
    .lte('date', endOfMonthKey(month))
    .order('date', { ascending: false })
    .order('created_at', { ascending: false })
  if (error) throw error
  return data
}

/** `id` is generated by the client so an optimistic row and the saved one share it. */
export async function createExpense(
  householdId: string,
  id: string,
  input: ExpenseInput,
): Promise<Expense> {
  const { data, error } = await supabase
    .from('expenses')
    .insert({ ...input, id, household_id: householdId })
    .select()
    .single()
  if (error) throw error
  return data
}

export async function updateExpense(id: string, input: ExpenseInput): Promise<Expense> {
  const { data, error } = await supabase
    .from('expenses')
    .update(input)
    .eq('id', id)
    .select()
    .single()
  if (error) throw error
  return data
}

export async function deleteExpense(id: string): Promise<void> {
  const { error } = await supabase.from('expenses').delete().eq('id', id)
  if (error) throw error
}

export async function fetchSuggestions(householdId: string): Promise<ExpenseSuggestion[]> {
  const { data, error } = await supabase
    .from('expense_suggestions')
    .select('*')
    .eq('household_id', householdId)
    .order('uses', { ascending: false })
    .limit(2000)
  if (error) throw error
  return data
}
